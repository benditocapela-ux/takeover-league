CREATE OR REPLACE FUNCTION public.admin_set_profile_role(p_profile_id uuid,p_role text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $role$
DECLARE actor uuid; target public.profiles%ROWTYPE;
BEGIN
 SELECT p.id INTO actor FROM public.profiles p
 WHERE p.auth_user_id=(SELECT auth.uid()) AND p.role='admin' AND p.is_active;
 IF actor IS NULL THEN RAISE EXCEPTION 'Nur der aktive Admin darf Rollen vergeben' USING ERRCODE='42501'; END IF;
 IF p_role IS NULL OR p_role NOT IN ('boxer','coach') THEN
   RAISE EXCEPTION 'Erlaubte Rollen: boxer oder coach. admin bleibt Eigentümer.' USING ERRCODE='22023';
 END IF;
 PERFORM pg_catalog.pg_advisory_xact_lock(94712019);
 SELECT * INTO target FROM public.profiles WHERE id=p_profile_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Profil nicht gefunden' USING ERRCODE='P0002'; END IF;
 IF target.role='admin' THEN
   RAISE EXCEPTION 'Der Eigentümer-Admin kann nicht heruntergestuft werden' USING ERRCODE='42501';
 END IF;
 IF target.role=p_role THEN RETURN; END IF;
 UPDATE public.profiles SET role=p_role WHERE id=target.id;
 INSERT INTO public.profile_admin_audit(profile_id,changed_by,action,old_value,new_value)
 VALUES(target.id,actor,'role',jsonb_build_object('role',target.role),jsonb_build_object('role',p_role));
END;
$role$;

