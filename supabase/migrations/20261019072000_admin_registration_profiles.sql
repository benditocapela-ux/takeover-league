CREATE OR REPLACE FUNCTION public.admin_set_profile_email(p_profile_id uuid,p_email text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $email$
DECLARE actor uuid; target public.profiles%ROWTYPE; normalized text;
BEGIN
 SELECT p.id INTO actor FROM public.profiles p
 WHERE p.auth_user_id=(SELECT auth.uid()) AND p.role='admin' AND p.is_active;
 IF actor IS NULL THEN RAISE EXCEPTION 'Nur der aktive Admin darf vorbereitete E-Mails setzen' USING ERRCODE='42501'; END IF;
 normalized:=nullif(lower(btrim(coalesce(p_email,''))),'');
 IF normalized IS NOT NULL AND
   (length(normalized)>254 OR normalized !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$') THEN
  RAISE EXCEPTION 'Ungültige E-Mail-Adresse' USING ERRCODE='22023';
 END IF;
 SELECT * INTO target FROM public.profiles WHERE id=p_profile_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Profil nicht gefunden' USING ERRCODE='P0002'; END IF;
 IF target.auth_user_id IS NOT NULL THEN
  RAISE EXCEPTION 'E-Mail eines bereits verknüpften Profils ist nicht änderbar' USING ERRCODE='42501';
 END IF;
 IF normalized IS NOT NULL AND EXISTS(
  SELECT 1 FROM public.profiles p WHERE lower(p.email)=normalized AND p.id<>p_profile_id
 ) THEN RAISE EXCEPTION 'E-Mail gehört bereits zu einem Profil' USING ERRCODE='23505'; END IF;
 IF normalized IS NOT NULL AND EXISTS(
   SELECT 1 FROM auth.users u WHERE lower(u.email)=normalized
 ) THEN RAISE EXCEPTION 'Diese E-Mail ist bereits registriert: Zuordnung nicht automatisch möglich' USING ERRCODE='23505'; END IF;
 IF target.email IS NOT DISTINCT FROM normalized THEN RETURN; END IF;
 UPDATE public.profiles SET email=normalized WHERE id=target.id;
 INSERT INTO public.profile_admin_audit(profile_id,changed_by,action,old_value,new_value)
 VALUES(target.id,actor,'email',jsonb_build_object('email',target.email),jsonb_build_object('email',normalized));
END;
