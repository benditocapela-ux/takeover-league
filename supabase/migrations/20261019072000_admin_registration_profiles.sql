-- Auth trigger: never grants roles, EXP or points. Existing prepared profile wins.
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $newuser$
DECLARE
 normalized text;
 existing_profile uuid;
 chosen_name text;
BEGIN
 IF NEW.email IS NULL OR btrim(NEW.email)='' THEN
  RAISE EXCEPTION 'Registrierung benötigt eine E-Mail-Adresse' USING ERRCODE='22023';
 END IF;
 normalized:=lower(btrim(NEW.email));
 IF EXISTS(SELECT 1 FROM public.profiles p WHERE p.auth_user_id=NEW.id) THEN
  RETURN NEW; -- idempotent, never overwrite an existing auth mapping
 END IF;
 -- Prepared profile: preserve profile UUID, role, points, EXP and listing.
 UPDATE public.profiles p SET auth_user_id=NEW.id,is_active=true
 WHERE p.email=normalized AND p.auth_user_id IS NULL
 RETURNING p.id INTO existing_profile;
 IF existing_profile IS NOT NULL THEN RETURN NEW; END IF;
 IF EXISTS(SELECT 1 FROM public.profiles p WHERE p.email=normalized) THEN
  RAISE EXCEPTION 'Diese E-Mail ist bereits einem anderen Profil zugeordnet' USING ERRCODE='23505';
 END IF;
 chosen_name:=nullif(btrim(COALESCE(NEW.raw_user_meta_data->>'display_name','')),'');
 IF chosen_name IS NULL THEN chosen_name:=split_part(normalized,'@',1); END IF;
 chosen_name:=left(COALESCE(nullif(btrim(chosen_name),''),'Neuer Boxer'),80);
 INSERT INTO public.profiles(auth_user_id,email,display_name,role,is_active,is_listed)
 VALUES (NEW.id,normalized,chosen_name,'boxer',true,false);
 RETURN NEW;
END;
$newuser$;
REVOKE ALL ON FUNCTION public.handle_new_user() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created AFTER INSERT ON auth.users
 FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

