-- Nachvollziehbare Änderungshistorie für Liga-Verwaltung (27.10.2026).
-- Profile (profile_admin_audit) und Trainings (training_audit) hatten bereits ein Protokoll; Saisons,
-- Liga-Challenges, Arenen und Boxerziele nicht. Neu: append-only Protokoll per Trigger, nur für aktive Admins lesbar.
-- Erfasst werden nur Verwaltungsfelder (Status, Titel, Zeitraum, Ziel, EXP-Regeln) – keine Trainingsnotizen.
-- Keine bestehenden Daten werden verändert. Produktion nur mit separater ausdrücklicher FREIGABE.
BEGIN;
CREATE TABLE IF NOT EXISTS public.league_admin_audit_v21(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_at timestamptz NOT NULL DEFAULT now(),
 actor_id uuid,
 actor_role text,
 entity text NOT NULL CHECK (entity IN ('season','league_challenge','arena','goal')),
 entity_id uuid NOT NULL,
 action text NOT NULL CHECK (action IN ('insert','update','delete')),
 old_value jsonb,
 new_value jsonb
);
CREATE INDEX IF NOT EXISTS league_admin_audit_v21_created_idx ON public.league_admin_audit_v21(created_at DESC);
ALTER TABLE public.league_admin_audit_v21 ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.league_admin_audit_v21 FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.league_admin_audit_v21 TO authenticated;
DROP POLICY IF EXISTS "Active admin reads change log" ON public.league_admin_audit_v21;
CREATE POLICY "Active admin reads change log" ON public.league_admin_audit_v21 FOR SELECT TO authenticated
USING (EXISTS (SELECT 1 FROM public.profiles p WHERE p.auth_user_id=(SELECT auth.uid()) AND p.is_active AND p.role='admin'));

CREATE OR REPLACE FUNCTION league_v21_private.audit_admin_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $fn$
declare actor public.profiles%rowtype; o jsonb; n jsonb; keys text[]; ent text;
begin
 ent:=case TG_TABLE_NAME when 'league_seasons_v21' then 'season' when 'league_global_challenges_v21' then 'league_challenge'
  when 'league_arena_duels_v21' then 'arena' else 'goal' end;
 keys:=case ent
  when 'season' then ARRAY['title','starts_on','ends_on','status']
  when 'league_challenge' then ARRAY['title','metric','target_value','starts_at','ends_at','status','completion_exp','winner_exp']
  when 'arena' then ARRAY['title','duration_days','status','starts_at','ends_at']
  else ARRAY['boxer_id','title','metric','target_value','ends_on','status','reward_exp'] end;
 if TG_OP<>'INSERT' then select pg_catalog.jsonb_object_agg(k,to_jsonb(OLD)->k) into o from pg_catalog.unnest(keys) k; end if;
 if TG_OP<>'DELETE' then select pg_catalog.jsonb_object_agg(k,to_jsonb(NEW)->k) into n from pg_catalog.unnest(keys) k; end if;
 if TG_OP='UPDATE' and o is not distinct from n then return NEW; end if;
 select * into actor from public.profiles p where p.auth_user_id=(select auth.uid()) limit 1;
 insert into public.league_admin_audit_v21(actor_id,actor_role,entity,entity_id,action,old_value,new_value)
 values(actor.id,actor.role,ent,case when TG_OP='DELETE' then OLD.id else NEW.id end,lower(TG_OP),o,n);
 return case when TG_OP='DELETE' then OLD else NEW end;
end$fn$;
REVOKE ALL ON FUNCTION league_v21_private.audit_admin_change() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS league_v21_audit_seasons ON public.league_seasons_v21;
CREATE TRIGGER league_v21_audit_seasons AFTER INSERT OR UPDATE OR DELETE ON public.league_seasons_v21
 FOR EACH ROW EXECUTE FUNCTION league_v21_private.audit_admin_change();
DROP TRIGGER IF EXISTS league_v21_audit_global_challenges ON public.league_global_challenges_v21;
CREATE TRIGGER league_v21_audit_global_challenges AFTER INSERT OR UPDATE OR DELETE ON public.league_global_challenges_v21
 FOR EACH ROW EXECUTE FUNCTION league_v21_private.audit_admin_change();
DROP TRIGGER IF EXISTS league_v21_audit_arena ON public.league_arena_duels_v21;
CREATE TRIGGER league_v21_audit_arena AFTER INSERT OR UPDATE OR DELETE ON public.league_arena_duels_v21
 FOR EACH ROW EXECUTE FUNCTION league_v21_private.audit_admin_change();
DROP TRIGGER IF EXISTS league_v21_audit_goals ON public.league_boxer_goals_v21;
CREATE TRIGGER league_v21_audit_goals AFTER INSERT OR UPDATE OR DELETE ON public.league_boxer_goals_v21
 FOR EACH ROW EXECUTE FUNCTION league_v21_private.audit_admin_change();
NOTIFY pgrst, 'reload schema';
COMMIT;
