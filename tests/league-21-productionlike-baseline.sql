create table public.profiles(
 id uuid primary key default gen_random_uuid(),
 auth_user_id uuid unique,
 display_name text not null default 'Boxer',
 is_active boolean not null default true,
 role text not null check(role in ('boxer','admin','coach'))
);
create table public.training_types(
 id bigint generated by default as identity primary key,
 name text not null,
 points integer not null default 20,
 is_active boolean not null default true
);
create table public.training_submissions(
 id uuid primary key default gen_random_uuid(),
 boxer_id uuid not null references public.profiles(id),
 training_type_id bigint not null references public.training_types(id),
 training_date date not null,
 notes text not null default '',
 status text not null default 'pending' check(status in ('pending','approved','rejected')),
 jogging_km numeric,
 technique_minutes integer,
 created_at timestamptz not null default now(),
 reviewed_at timestamptz,
 reviewed_by uuid references public.profiles(id),
 client_request_id uuid
);
create table public.point_transactions(
 id uuid primary key default gen_random_uuid(),
 boxer_id uuid not null references public.profiles(id),
 submission_id uuid references public.training_submissions(id),
 points integer not null default 0,
 exp integer not null default 0,
 category text not null check(category in ('training','trainer_bonus','adjustment','legacy_import',
      'automatic_bonus','achievement_exp','duel_exp','challenge_exp')),
 description text not null default '',
 effective_date date not null default current_date,
 created_by uuid references public.profiles(id),
 created_at timestamptz not null default now()
);
create table public.achievement_definitions(
 id uuid primary key default gen_random_uuid(),
 title text not null,
 icon_key text,
 is_active boolean not null default true
);
create table public.boxer_achievements(
 id uuid primary key default gen_random_uuid(),
 boxer_id uuid not null references public.profiles(id),
 achievement_id uuid not null references public.achievement_definitions(id),
 earned_at timestamptz not null default now(),
 unique(boxer_id,achievement_id)
);
create table public.league_feature_flags(
 feature_key text primary key,
 display_name text not null,
 is_enabled boolean not null default false,
 updated_at timestamptz not null default now()
);
create table public.league_duels(
 id uuid primary key default gen_random_uuid(),
 challenger_id uuid not null references public.profiles(id),
 opponent_id uuid not null references public.profiles(id),
 created_by uuid references public.profiles(id),
 initiated_by_coach boolean not null default false,
 status text not null default 'pending' check(status in
  ('pending','active','awaiting_reviews','settled','declined','expired','cancelled')),
 duration_days integer not null check(duration_days in (7,14)),
 invited_at timestamptz not null default now(),
 expires_at timestamptz not null default(now()+interval '48 hours'),
 accepted_at timestamptz,
 ends_at timestamptz,
 settled_at timestamptz,
 challenger_score integer not null default 0,
 opponent_score integer not null default 0,
 winner_id uuid references public.profiles(id),
 updated_at timestamptz not null default now(),
 check(challenger_id<>opponent_id),
 check(winner_id is null or winner_id in (challenger_id,opponent_id)),
 check(ends_at is null or (accepted_at is not null and ends_at=accepted_at+duration_days*interval '1 day'))
);
create table public.league_duel_events(
 id bigint generated by default as identity primary key,
 duel_id uuid not null references public.league_duels(id),
 event_type text not null,
 payload jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now()
);
create table public.league_duel_exp_ledger(
 duel_id uuid not null references public.league_duels(id),
 boxer_id uuid not null references public.profiles(id),
 awarded_exp integer not null check(awarded_exp in (0,25,50,100)),
 transaction_id uuid unique references public.point_transactions(id),
 updated_at timestamptz not null default now(),
 primary key(duel_id,boxer_id)
);
