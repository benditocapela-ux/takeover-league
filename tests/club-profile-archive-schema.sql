CREATE TABLE public.profiles(
 id uuid PRIMARY KEY,
 auth_user_id uuid UNIQUE,
 role text NOT NULL,
 is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE public.profile_admin_audit(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 profile_id uuid NOT NULL REFERENCES public.profiles(id),
 changed_by uuid NOT NULL REFERENCES public.profiles(id),
 action text NOT NULL CHECK(action IN ('role','active','listed','email')),
 old_value jsonb,
 new_value jsonb,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.training_submissions(id integer PRIMARY KEY, boxer_id uuid NOT NULL, status text NOT NULL);
CREATE TABLE public.point_transactions(id integer PRIMARY KEY, boxer_id uuid NOT NULL, points integer NOT NULL, exp integer NOT NULL);

